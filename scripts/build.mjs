// Build every distributable from the one icon source:
//   site/public/svg/<style>/<name>.svg  (8 styles), sprites, icons.json, bridle.js (web component), bridle-svg.zip
//   src/names.d.ts                      (IconName union for TypeScript users)
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICONS, CATEGORIES, GROUPS, renderSvg } from '../src/index.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const pub = path.join(root, 'site/public');
const STYLES = ['line', 'solid', 'color', 'iso'].flatMap((v) => [[v, false], [v, true]]);
const dir = (v, a) => (a ? `${v}-animated` : v);

// Cloudflare Pages takes at most 20,000 files per deploy, so line/solid motion ship in the zip and renderer only.
const HOSTED = STYLES.filter(([v, a]) => !a || v === 'color' || v === 'iso');
rmSync(path.join(pub, 'svg'), { recursive: true, force: true });
rmSync(path.join(root, '.zipstage'), { recursive: true, force: true });
for (const [v, a] of STYLES) {
  const hosted = HOSTED.some(([hv, ha]) => hv === v && ha === a);
  const base = path.join(hosted ? pub : path.join(root, '.zipstage'), 'svg', dir(v, a));
  mkdirSync(base, { recursive: true });
  for (const i of ICONS) writeFileSync(path.join(base, `${i.name}.svg`), renderSvg(i, { variant: v, animated: a, uid: `bri-${i.name}` }) + '\n');
}
// sprites: <svg><use href="bridle-line.svg#wallet"/></svg>
for (const v of ['line', 'solid']) {
  const syms = ICONS.map((i) => renderSvg(i, { variant: v, uid: `bri-${i.name}`, title: false })
    .replace(/^<svg[^>]*?viewBox="([^"]+)"[^>]*>/, (_, vb) => `<symbol id="${i.name}" viewBox="${vb}" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">`)
    .replace(/<\/svg>$/, '</symbol>'));
  writeFileSync(path.join(pub, `bridle-${v}.svg`), `<svg xmlns="http://www.w3.org/2000/svg">${syms.join('')}</svg>\n`);
}
const manifest = { name: 'Bridle', version: '1.0.0', license: 'MIT', count: ICONS.length, styles: STYLES.map(([v, a]) => dir(v, a)), groups: GROUPS.map((g) => ({ id: g.id, label: g.label, categories: g.cats.map((c) => c.id) })), categories: CATEGORIES.map((c) => ({ id: c.id, label: c.label, icons: c.icons.map((i) => ({ name: i.name, tags: i.tags })) })) };
writeFileSync(path.join(pub, 'icons.json'), JSON.stringify(manifest));
writeFileSync(path.join(pub, 'favicon.svg'), renderSvg(ICONS.find((i) => i.name === 'sparkles'), { variant: 'color', palette: 'grape', uid: 'fav', title: 'Bridle' }));
writeFileSync(path.join(root, 'src/names.d.ts'), `// generated by scripts/build.mjs\nexport type IconName =\n${ICONS.map((i) => `  | '${i.name}'`).join('\n')};\n`);

// web component bundle (esbuild ships with the site's vite)
const require = createRequire(path.join(root, 'site/package.json'));
require('esbuild').buildSync({ entryPoints: [path.join(root, 'src/element.mjs')], bundle: true, minify: true, format: 'esm', outfile: path.join(pub, 'bridle.js'), legalComments: 'none', banner: { js: '/* Bridle icons, MIT, https://bridle.verity.dev */' } });

// one zip with every SVG, sprite and the manifest
const zip = path.join(pub, 'bridle-svg.zip');
rmSync(zip, { force: true });
// zip = hosted styles + the unhosted motion styles staged outside public/
execFileSync('bash', ['-c', `cp -r svg/. ${path.join(root, '.zipstage/svg')}/ && cp bridle-line.svg bridle-solid.svg icons.json ${path.join(root, '.zipstage')}/`], { cwd: pub });
execFileSync('python3', ['-m', 'zipfile', '-c', zip, 'svg', 'bridle-line.svg', 'bridle-solid.svg', 'icons.json'], { cwd: path.join(root, '.zipstage') });
rmSync(path.join(root, '.zipstage'), { recursive: true, force: true });
console.log(`bridle: ${ICONS.length} icons x ${STYLES.length} styles = ${ICONS.length * STYLES.length} SVGs`);
