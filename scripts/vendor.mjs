#!/usr/bin/env node
// Vendor a handful of Bridle icons into an app as one small, pre-rendered module (no runtime renderer, no 800 KB registry).
//
//   node scripts/vendor.mjs --out src/icons/bridle.tsx [--react|--js] <spec> <spec> ...
//
//   spec = name                 line (default)
//          name@solid           any style: line duo solid duotone color
//          name@color~anim      animated (honours prefers-reduced-motion)
//          name@color:ocean     colour palette preset or hue (color only)
//
// --react (default) writes a .tsx with <Icon name="wallet" size={18} /> ; --js writes a plain ES module with
// bridleSvg(name, { size, label }) returning an SVG string, for apps without React.
// Keys are the spec without the palette, e.g. "wallet", "rocket@color", "radar@line~anim".
// Icons inherit currentColor. Re-run with the full list to change the set; never edit the output by hand.
import fs from 'node:fs';
import path from 'node:path';
import { byName, renderSvg } from '../src/index.mjs';

const argv = process.argv.slice(2);
let out = null, mode = 'react';
const specs = [];
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === '--out') out = argv[++i];
  else if (a === '--react') mode = 'react';
  else if (a === '--js') mode = 'js';
  else specs.push(...a.split(/[\s,]+/).filter(Boolean));
}
if (!out || !specs.length) { console.error('usage: vendor.mjs --out <file> [--react|--js] name[@style][~anim][:palette] ...'); process.exit(2); }

const U = '__BRI_UID__', SZ = '__BRI_SIZE__';
const map = {};
const bad = [];
for (const spec of [...new Set(specs)]) {
  const m = spec.match(/^([a-z0-9-]+)(?:@(line|duo|solid|duotone|color))?(~anim)?(?::([a-z0-9]+))?$/);
  if (!m || !byName[m[1]]) { bad.push(spec); continue; }
  const [, name, variant = 'line', anim, pal] = m;
  const key = name + (variant !== 'line' ? '@' + variant : '') + (anim ? '~anim' : '');
  const palette = pal ? (/^\d+$/.test(pal) ? Number(pal) : pal) : undefined;
  map[key] = renderSvg(byName[name], { variant, animated: !!anim, size: SZ, title: false, uid: U, palette })
    .replace(/\s+/g, ' ');
}
if (bad.length) { console.error(`unknown icon spec: ${bad.join(', ')}\nsearch names: node scripts/find.mjs <words>`); process.exit(1); }

const keys = Object.keys(map).sort();
const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`).join('\n');
const head = `// Generated by Bridle (https://bridle.verity.dev) scripts/vendor.mjs. Do not edit by hand: re-run it with the full list.\n// node scripts/vendor.mjs --out <this file> --${mode} ${keys.join(' ')}\n`;
const fill = `function fill(svg: string, size: number | string, uid: string, label?: string) {
  const s = svg.split('${SZ}').join(String(size)).split('${U}').join(uid);
  return label ? s.replace(' role="img">', \` role="img" aria-label="\${label.replace(/"/g, '&quot;')}">\`) : s.replace(' role="img">', ' aria-hidden="true" focusable="false">');
}`;

let src;
if (mode === 'react') {
  src = `${head}import { useId, type CSSProperties, type HTMLAttributes } from 'react';

const SVG = {
${body}
} as const;

export type BridleName = keyof typeof SVG;

${fill}

export type IconProps = Omit<HTMLAttributes<HTMLSpanElement>, 'children'> & { name: BridleName; size?: number | string; label?: string; style?: CSSProperties };

/** A Bridle icon. Inherits currentColor; decorative unless \`label\` is given. */
export function Icon({ name, size = 18, label, style, ...rest }: IconProps) {
  const uid = 'b' + useId().replace(/[^a-zA-Z0-9]/g, '');
  return <span {...rest} style={{ display: 'inline-flex', lineHeight: 0, flexShrink: 0, ...style }} dangerouslySetInnerHTML={{ __html: fill(SVG[name], size, uid, label) }} />;
}
export default Icon;
`;
} else {
  src = `${head}const SVG = {
${body}
};
let n = 0;
${fill.replace(/: string \| number|: number \| string|: string|\?: string/g, '')}
/** bridleSvg('wallet', { size: 18, label: 'Wallet' }) -> SVG markup. Inherits currentColor. */
export function bridleSvg(name, opt = {}) {
  const svg = SVG[name];
  if (!svg) throw new Error('bridle: not vendored: ' + name);
  return fill(svg, opt.size ?? 18, 'b' + (++n).toString(36), opt.label);
}
export const BRIDLE_NAMES = Object.keys(SVG);
`;
}
fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
fs.writeFileSync(out, src);
console.log(`bridle: ${keys.length} icons -> ${out} (${(Buffer.byteLength(src) / 1024).toFixed(1)} KB)`);
